import XCTest

/// Not a journey: visits every screen and state worth reviewing and saves screenshots for the design review
/// (only when tools/e2e-ios.sh passes SCREENSHOT_DIR; the files never go into the repo). Run once per appearance.
@MainActor
final class ScreenTour: XCTestCase {
    func testScreens() throws {
        continueAfterFailure = false
        let d = HealthDriver()
        let today = HealthDriver.dateString(Date())
        let time = HealthDriver.timeString(HealthDriver.minuteBoundary(plus: 10))
        d.app.launch()
        d.wait(d.element("today.message"))
        d.screenshot("01-today-empty")

        d.tap("today.addMedication")
        d.screenshot("02-editor-pristine")
        d.tap("editor.save")
        d.wait(d.element("editor.error.name"))
        d.screenshot("03-editor-errors")
        d.tap("editor.addTime")
        d.wait(d.element("editor.timePicker"))
        d.screenshot("04-editor-time-picker")
        d.tap("editor.timePicker.cancel")
        d.type("editor.name", "Vitamin D")
        d.type("editor.dose", "1 capsule")
        d.addTime(time)
        d.type("editor.notes", "With breakfast", submit: false)
        d.screenshot("05-editor-filled")
        d.tap("editor.save")
        d.answerPermission(allow: true)
        let row = d.doseRow("today", date: today, time: time)
        d.wait(row)

        d.selectTab("medications")
        d.tap("medications.add")
        d.type("editor.name", "Medication B")
        d.type("editor.dose", "1 tablet")
        d.tap("editor.asNeeded")
        d.screenshot("06-editor-as-needed")
        d.tap("editor.save")
        d.wait(d.first(prefix: "medications.item."))
        d.screenshot("07-medications")
        d.tap(d.first(prefix: "medications.item."))
        d.wait(d.element("detail.name"))
        d.screenshot("08-detail")
        d.tap("detail.delete")
        d.wait(d.app.alerts.firstMatch)
        d.screenshot("09-detail-delete-dialog")
        d.tap(d.app.alerts.buttons.matching(identifier: "deleteDialog.cancel").firstMatch)
        d.goBack()

        d.selectTab("today")
        d.tap(d.first(prefix: "today.asNeeded.").descendants(matching: .button).matching(NSPredicate(format: "identifier ENDSWITH '.log'")).firstMatch)
        d.wait(d.element(row.identifier))
        d.screenshot("10-today")
        d.tap(row)
        d.wait(d.element("doseMenu.takeAt"))
        d.screenshot("11-dose-menu")
        d.tap("doseMenu.takeAt")
        d.wait(d.element("takeAt.picker"))
        d.screenshot("12-take-at")
        d.tap("takeAt.cancel")
        d.doseMenu(row, "doseMenu.take")
        d.expectText("today.progress", "1 of 1 taken")
        d.screenshot("13-today-all-done")

        d.tap("today.openReminders")
        d.wait(d.element("reminders.status"))
        d.screenshot("14-reminders")
        d.goBack()

        d.selectTab("history")
        d.wait(d.doseRow("history", date: today, time: time))
        d.screenshot("15-history")
        d.tap("history.date")
        d.wait(d.element("history.datePicker"))
        d.screenshot("16-history-date-picker")
        d.tap("history.datePicker.cancel")
        d.tap("history.previous")
        d.wait(d.element("history.message"))
        d.screenshot("17-history-empty")
    }
}
